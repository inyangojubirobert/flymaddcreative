const reportTemplate = `
-- ---------------------------------------------------------------------------
-- Dry run: verdict and guaranteed rollback
-- ---------------------------------------------------------------------------
do $report$
declare
  v_required constant text[] := __REQUIRED__;
  v_pass integer;
  v_fail integer;
  v_missing text;
  v_lines text;
  v_head text;
begin
  select count(*) filter (where ok and test not like 'INFO %'), count(*) filter (where not ok)
  into v_pass, v_fail from dry_run_results;

  select string_agg(r, ', ') into v_missing
  from unnest(v_required) r
  where not exists (select 1 from dry_run_results x where x.test like r || ' %');

  select string_agg(case when not ok then 'FAIL ' when test like 'INFO %' then '' else 'PASS ' end || test || coalesce(' -- ' || detail, ''),
                    E'\\n' order by (case when not ok then 0 when test like 'INFO %' then 2 else 1 end), seq)
  into v_lines from dry_run_results;

  if v_fail = 0 and v_missing is null then
    v_head := format('DRY_RUN_RESULT: PASS - %s assertions passed, 0 failed, all %s required tests ran. The transaction is being rolled back on purpose; nothing was saved.', v_pass, cardinality(v_required));
  else
    v_head := format('DRY_RUN_RESULT: FAIL - %s passed, %s failed%s. The transaction is being rolled back on purpose; nothing was saved.',
      v_pass, v_fail, coalesce('; required tests that did not run: ' || v_missing, ''));
  end if;

  raise exception using
    message = v_head || E'\\n' || v_lines,
    hint = 'Intentional abort so that nothing can be committed. Only messages starting with DRY_RUN_RESULT are dry-run verdicts; any other error is a genuine failure.';
end $report$;

rollback;
`;

