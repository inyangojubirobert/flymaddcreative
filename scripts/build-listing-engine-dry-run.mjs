function stripTransaction(path) {
  const sql = readFileSync(path, 'utf8').replace(/\r\n/g, '\n');
  const begins = sql.match(/^begin;$/gm) || [];
  const commits = sql.match(/^commit;$/gm) || [];
  if (begins.length !== 1 || commits.length !== 1) {
    throw new Error(`Expected exactly one top-level "begin;" and one "commit;" in ${path}.`);
  }
  return sql
    .replace(/^begin;$/m, '-- (begin; removed by dry-run builder)')
    .replace(/^commit;$/m, '-- (commit; removed by dry-run builder)');
}

